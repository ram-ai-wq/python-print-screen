"""QA evidence sessions: numbered, captioned screenshots plus a JSON manifest.

A session is one folder per test run::

    2026-11-22_140312_tc-101_login-flow/
        session.json                    # metadata + steps (the source of truth)
        001_open-login-page.png
        002_submit-wrong-password.png
        report.html / report.pdf / report.md   # generated by :mod:`report`

The tray app, the MCP server, the CLI and Python test code (for example a
Playwright test) all use this module, so evidence looks the same however it was
captured::

    from screenshot_tool.evidence import EvidenceSession

    session = EvidenceSession.create("evidence", "Login flow", test_case_id="TC-101")
    session.add_step(page.screenshot(), title="Open login page", status="passed")
    session.finish()
    session.export(["html", "pdf"])
"""

from __future__ import annotations

import getpass
import hashlib
import json
import logging
import os
import re
import sys
import time
import unicodedata
import uuid
from collections.abc import Iterable, Iterator, Mapping, Sequence
from contextlib import contextmanager
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

from PyQt6.QtCore import QStandardPaths
from PyQt6.QtGui import QImage

from . import __version__
from .render import ImageError, ImageSource, apply_annotations, encode_png, load_image, stamp_footer

log = logging.getLogger(__name__)

SCHEMA = "screenshot-tool/evidence-session"
SCHEMA_VERSION = 1
MANIFEST_NAME = "session.json"
LOCK_NAME = ".session.lock"
LOCK_TIMEOUT = 15.0  # seconds to wait for another process that is updating the session
STATUSES = ("passed", "failed", "blocked", "skipped", "info")
_STATUS_ALIASES = {
    "pass": "passed", "ok": "passed", "success": "passed", "succeeded": "passed",
    "fail": "failed", "failure": "failed", "error": "failed", "ko": "failed", "nok": "failed",
    "block": "blocked",
    "skip": "skipped", "not_run": "skipped", "notrun": "skipped", "na": "skipped", "n/a": "skipped",
    "information": "info", "informational": "info", "note": "info", "none": "info", "": "info",
}
_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
_STEP_ID_RE = re.compile(r"^[0-9a-f]{6,32}$")
_SHA_RE = re.compile(r"^[0-9a-f]{64}$")
# Step images are plain file names inside the session folder - never paths.
_IMAGE_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,150}\.png$")


class EvidenceError(Exception):
    """Raised for invalid evidence operations; the message is user-facing."""


# ------------------------------------------------------------------ helpers
def normalize_status(value: str | None, default: str = "info") -> str:
    """Map ``value`` (``"pass"``, ``"FAILED"``, ``"n/a"``...) to one of :data:`STATUSES`."""
    if value is None:
        return default
    key = str(value).strip().lower().replace("-", "_").replace(" ", "_")
    if key in STATUSES:
        return key
    if key in _STATUS_ALIASES:
        return _STATUS_ALIASES[key]
    raise EvidenceError(f"Unknown status {value!r}. Use one of: {', '.join(STATUSES)}.")


def slugify(text: str, max_len: int = 40, fallback: str = "step") -> str:
    """ASCII, lowercase, dash-separated version of ``text`` that is safe in file names."""
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", ascii_text).strip("-").lower()
    return slug[:max_len].strip("-") or fallback


def now_iso() -> str:
    """Local time with UTC offset, e.g. ``2026-11-22T14:03:12-03:00``."""
    return datetime.now().astimezone().isoformat(timespec="seconds")


def parse_iso(value: str | None) -> datetime | None:
    """Parse a timestamp written by :func:`now_iso` (``None`` if empty or invalid)."""
    if not value:
        return None
    try:
        return datetime.fromisoformat(value)
    except ValueError:
        return None


def format_timestamp(value: str | None, with_offset: bool = True) -> str:
    """``2026-11-22 14:03:12 -03:00`` (human readable)."""
    dt = parse_iso(value)
    if dt is None:
        return value or ""
    text = dt.strftime("%Y-%m-%d %H:%M:%S")
    if with_offset and dt.utcoffset() is not None:
        offset = dt.strftime("%z")  # -0300
        text += f" {offset[:3]}:{offset[3:]}"
    return text


def default_tester() -> str:
    """The operating-system user name (empty if it cannot be determined)."""
    try:
        return getpass.getuser()
    except Exception:  # noqa: BLE001 - getpass raises various errors on odd systems
        return ""


def default_evidence_root() -> Path:
    """``<Documents>/QA-Evidence`` (respects redirected/OneDrive Documents folders)."""
    docs = QStandardPaths.writableLocation(QStandardPaths.StandardLocation.DocumentsLocation)
    base = Path(docs) if docs else Path.home() / "Documents"
    if not base.is_dir():
        base = Path.home()
    return base / "QA-Evidence"


def write_text_atomic(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` atomically (retrying briefly if Windows locks the file)."""
    tmp = path.with_name(f".{path.name}.{uuid.uuid4().hex[:8]}.tmp")
    tmp.write_text(text, encoding="utf-8")
    for attempt in range(10):
        try:
            os.replace(tmp, path)
            return
        except PermissionError:
            if attempt == 9:
                tmp.unlink(missing_ok=True)
                raise
            time.sleep(0.05 * (attempt + 1))


def _read_text_retrying(path: Path) -> str:
    """Read a file another process may be atomically replacing at this very moment
    (Windows briefly denies access to a file while it is being replaced)."""
    for attempt in range(10):
        try:
            return path.read_text(encoding="utf-8")
        except PermissionError:
            if attempt == 9:
                raise
            time.sleep(0.02 * (attempt + 1))
    raise AssertionError("unreachable")


def _clean(value: Any, limit: int = 4000) -> str:
    text = "" if value is None else str(value)
    return text.strip()[:limit]


def _new_step_id() -> str:
    return uuid.uuid4().hex[:12]


@contextmanager
def _session_lock(folder: Path, timeout: float = LOCK_TIMEOUT) -> Iterator[None]:
    """Exclusive cross-process lock for read-modify-write of a session.

    Uses an OS file lock (released automatically if the process dies), so the tray
    app, the MCP server and scripts can update the same session concurrently.
    """
    try:
        handle = open(folder / LOCK_NAME, "a+b")  # noqa: SIM115 - closed in finally
    except OSError as exc:
        raise EvidenceError(f"Cannot lock the session in {folder}: {exc}") from exc
    deadline = time.monotonic() + timeout
    locked = False
    try:
        while not locked:
            try:
                if sys.platform == "win32":
                    import msvcrt

                    handle.seek(0)
                    msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
                else:
                    import fcntl

                    fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                locked = True
            except OSError:
                if time.monotonic() > deadline:
                    raise EvidenceError("The session is being updated by another program; try again.") from None
                time.sleep(0.03)
        yield
    finally:
        if locked:
            try:
                if sys.platform == "win32":
                    import msvcrt

                    handle.seek(0)
                    msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
                else:
                    import fcntl

                    fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
            except OSError:
                pass
        handle.close()


def _opt_int(value: Any) -> int | None:
    return value if isinstance(value, int) and not isinstance(value, bool) and value >= 0 else None


# -------------------------------------------------------------------- model
@dataclass
class EvidenceStep:
    """One piece of evidence: usually a screenshot, optionally text only.

    ``number`` is the position (1-based, renumbered after deletions/moves); ``id`` is
    stable for the life of the step, so it can be used to address a step safely.
    """

    number: int
    title: str
    status: str = "info"
    expected: str = ""
    actual: str = ""
    notes: str = ""
    url: str = ""
    image: str | None = None  # plain file name inside the session folder
    width: int | None = None
    height: int | None = None
    sha256: str | None = None
    captured_at: str = ""
    source: str = "api"
    id: str = field(default_factory=_new_step_id)

    @classmethod
    def from_dict(cls, data: Mapping[str, Any], position: int) -> EvidenceStep:
        """Build a step from manifest data, validating every field.

        Raises:
            EvidenceError: the image reference is not a plain file name of this session
                (a manifest must never point outside its own folder).
        """
        image = data.get("image")
        if image is not None and (not isinstance(image, str) or not _IMAGE_NAME_RE.match(image)):
            raise EvidenceError(f"Step {position} refers to an invalid image file name: {image!r}.")
        try:
            status = normalize_status(data.get("status"))
        except EvidenceError:
            status = "info"
        sha = data.get("sha256")
        step_id = data.get("id")
        number = data.get("number")
        return cls(
            number=number if _opt_int(number) else position,
            title=_clean(data.get("title"), 300) or f"Step {position}",
            status=status,
            expected=_clean(data.get("expected")),
            actual=_clean(data.get("actual")),
            notes=_clean(data.get("notes")),
            url=_clean(data.get("url"), 2000),
            image=image,
            width=_opt_int(data.get("width")),
            height=_opt_int(data.get("height")),
            sha256=sha if isinstance(sha, str) and _SHA_RE.match(sha) else None,
            captured_at=_clean(data.get("captured_at"), 40),
            source=_clean(data.get("source"), 40) or "api",
            id=step_id if isinstance(step_id, str) and _STEP_ID_RE.match(step_id) else _new_step_id(),
        )

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class EvidenceSession:
    """A test run's evidence folder. Every mutating method saves immediately.

    Mutations re-read ``session.json`` first, so a session can safely be used by
    more than one process (for example the tray app and the MCP server).
    """

    path: Path
    title: str
    test_case_id: str = ""
    tester: str = ""
    environment: str = ""
    build: str = ""
    description: str = ""
    created_at: str = ""
    finished_at: str | None = None
    result: str | None = None
    summary: str = ""
    stamp_images: bool = True
    tool_version: str = __version__
    steps: list[EvidenceStep] = field(default_factory=list)

    _PERSISTED = ("title", "test_case_id", "tester", "environment", "build", "description",
                  "created_at", "finished_at", "result", "summary", "stamp_images", "tool_version")

    # ---------------------------------------------------------- creation / IO
    @classmethod
    def create(
        cls,
        root: str | os.PathLike[str] | None,
        title: str,
        *,
        test_case_id: str = "",
        tester: str | None = None,
        environment: str = "",
        build: str = "",
        description: str = "",
        stamp_images: bool = True,
    ) -> EvidenceSession:
        """Create a new session folder under ``root`` (default: :func:`default_evidence_root`).

        Raises:
            EvidenceError: empty title or the folder cannot be created.
        """
        title = _clean(title, 200)
        test_case_id = _clean(test_case_id, 100)
        if not title and not test_case_id:
            raise EvidenceError("A session needs a title or a test case ID.")
        base = Path(root).expanduser() if root else default_evidence_root()
        created = now_iso()
        stamp = parse_iso(created).strftime("%Y-%m-%d_%H%M%S")  # type: ignore[union-attr]
        parts = [stamp]
        if test_case_id:
            parts.append(slugify(test_case_id, 30, "tc"))
        if title:
            parts.append(slugify(title, 40, "session"))
        name = "_".join(parts)
        try:
            base.mkdir(parents=True, exist_ok=True)
            folder = base / name
            n = 2
            while True:
                try:
                    folder.mkdir()
                    break
                except FileExistsError:
                    folder = base / f"{name}-{n}"
                    n += 1
        except OSError as exc:
            raise EvidenceError(f"Could not create the evidence folder in '{base}': {exc}") from exc
        session = cls(
            path=folder,
            title=title or test_case_id,
            test_case_id=test_case_id,
            tester=_clean(default_tester() if tester is None else tester, 200),
            environment=_clean(environment, 500),
            build=_clean(build, 200),
            description=_clean(description),
            created_at=created,
            stamp_images=bool(stamp_images),
        )
        session._save()
        return session

    @classmethod
    def open(cls, ref: str | os.PathLike[str], root: str | os.PathLike[str] | None = None) -> EvidenceSession:
        """Open a session by folder path, or by its ID (folder name) under ``root``.

        Raises:
            EvidenceError: not found or not a valid session.
        """
        candidate = Path(ref).expanduser()
        if candidate.name == MANIFEST_NAME:
            candidate = candidate.parent
        if not (candidate / MANIFEST_NAME).is_file():
            text = str(ref).strip()
            if not _ID_RE.match(text):
                raise EvidenceError(f"Evidence session not found: {ref}")
            base = Path(root).expanduser() if root else default_evidence_root()
            candidate = base / text
            if not (candidate / MANIFEST_NAME).is_file():
                raise EvidenceError(f"Evidence session '{text}' not found in {base}")
        session = cls(path=candidate.resolve(), title="")
        session.reload()
        return session

    def reload(self) -> None:
        """Re-read ``session.json`` (picks up changes made by other processes).

        Every field is validated: a manifest received from someone else cannot make
        the tool read, move or delete files outside the session folder.

        Raises:
            EvidenceError: unreadable or invalid manifest.
        """
        manifest = self.path / MANIFEST_NAME
        try:
            data = json.loads(_read_text_retrying(manifest))
        except (OSError, ValueError, RecursionError) as exc:
            raise EvidenceError(f"Could not read {manifest}: {exc}") from exc
        if not isinstance(data, dict) or data.get("schema") != SCHEMA:
            raise EvidenceError(f"{manifest} is not an evidence session manifest.")
        raw_steps = data.get("steps") or []
        if not isinstance(raw_steps, list):
            raise EvidenceError(f"{manifest}: 'steps' must be a list.")
        steps = [EvidenceStep.from_dict(s, i) for i, s in enumerate(raw_steps, 1) if isinstance(s, dict)]
        limits = {"title": 200, "test_case_id": 100, "tester": 200, "environment": 500, "build": 200,
                  "description": 4000, "summary": 8000, "created_at": 40, "tool_version": 40}
        for key, limit in limits.items():
            setattr(self, key, _clean(data.get(key), limit))
        self.stamp_images = data.get("stamp_images", True) is not False
        finished = data.get("finished_at")
        self.finished_at = _clean(finished, 40) or None if finished else None
        try:
            self.result = normalize_status(data["result"]) if data.get("result") else None
        except EvidenceError:
            self.result = None
        steps.sort(key=lambda s: s.number)
        for i, step in enumerate(steps, 1):
            step.number = i
        self.steps = steps

    def _save(self) -> None:
        data: dict[str, Any] = {"schema": SCHEMA, "schema_version": SCHEMA_VERSION, "id": self.id}
        data.update({key: getattr(self, key) for key in self._PERSISTED})
        data["steps"] = [s.to_dict() for s in self.steps]
        try:
            write_text_atomic(self.path / MANIFEST_NAME, json.dumps(data, indent=2, ensure_ascii=False))
        except OSError as exc:
            raise EvidenceError(f"Could not save {self.path / MANIFEST_NAME}: {exc}") from exc

    # -------------------------------------------------------------- properties
    @property
    def id(self) -> str:
        """The folder name; unique within an evidence root."""
        return self.path.name

    @property
    def is_finished(self) -> bool:
        return bool(self.finished_at)

    @property
    def label(self) -> str:
        """Short human label, e.g. ``TC-101 · Login flow``."""
        if self.test_case_id and self.test_case_id != self.title:
            return f"{self.test_case_id} · {self.title}"
        return self.title

    def step(self, ref: int | str) -> EvidenceStep:
        """Return a step by number (1-based ``int``) or by its stable ``id`` (``str``).

        Prefer the id when the step list on screen may be out of date: numbers change
        when steps are deleted or reordered (possibly by another process).

        Raises:
            EvidenceError: no such step.
        """
        if isinstance(ref, str):
            for step in self.steps:
                if step.id == ref:
                    return step
            raise EvidenceError("That step no longer exists (it was deleted, perhaps by another program).")
        if isinstance(ref, bool) or not isinstance(ref, int) or not 1 <= ref <= len(self.steps):
            total = len(self.steps)
            hint = f"1-{total}" if total else "none yet"
            raise EvidenceError(f"Step {ref} does not exist (steps: {hint}).")
        return self.steps[ref - 1]

    def image_path(self, step: EvidenceStep) -> Path | None:
        """Absolute path of a step's image, if it has one."""
        return self.path / step.image if step.image else None

    def counts(self) -> dict[str, int]:
        """Number of steps per status, plus ``total``."""
        out = {status: 0 for status in STATUSES}
        for step in self.steps:
            out[step.status] = out.get(step.status, 0) + 1
        out["total"] = len(self.steps)
        return out

    def computed_result(self) -> str:
        """Overall result implied by the steps: failed > blocked > passed > info."""
        statuses = {s.status for s in self.steps}
        for status in ("failed", "blocked", "passed"):
            if status in statuses:
                return status
        return "skipped" if statuses == {"skipped"} else "info"

    def duration_seconds(self) -> int | None:
        start = parse_iso(self.created_at)
        end = parse_iso(self.finished_at) or datetime.now().astimezone()
        if start is None:
            return None
        return max(0, int((end - start).total_seconds()))

    # ------------------------------------------------------------------ steps
    def add_step(
        self,
        image: ImageSource | None = None,
        *,
        title: str = "",
        status: str | None = "info",
        expected: str = "",
        actual: str = "",
        notes: str = "",
        url: str = "",
        source: str = "api",
        annotations: Iterable[Mapping[str, Any]] | None = None,
        stamp: bool | None = None,
    ) -> EvidenceStep:
        """Append a step. ``image`` may be ``None`` for a text-only step.

        Args:
            image: Screenshot (PNG/JPEG bytes, a file path, ``QImage`` or Pillow image).
            title: What the step shows, e.g. ``"Error message is displayed"``.
            status: passed / failed / blocked / skipped / info (aliases accepted).
            expected: Expected result.
            actual: Actual result observed.
            notes: Any extra detail (log lines, IDs, data used).
            url: Page or resource the evidence refers to.
            source: Who produced it (``manual``, ``mcp``, ``cli``, ``api``...).
            annotations: Shapes to draw first; see :func:`render.build_annotations`.
            stamp: Append the evidence footer (default: the session's ``stamp_images``).

        Raises:
            EvidenceError: invalid status/annotation, unreadable image, or disk error.
        """
        status = normalize_status(status)
        step = EvidenceStep(
            number=0,  # assigned under the lock
            title=_clean(title, 300),
            status=status,
            expected=_clean(expected),
            actual=_clean(actual),
            notes=_clean(notes),
            url=_clean(url, 2000),
            captured_at=now_iso(),
            source=_clean(source, 40) or "api",
        )
        data: bytes | None = None
        if image is not None:  # the slow part (decode, draw, encode) runs before locking
            try:
                qimage = load_image(image)
                if annotations:
                    qimage = apply_annotations(qimage, list(annotations))
            except ImageError as exc:
                raise EvidenceError(str(exc)) from exc
            if self.stamp_images if stamp is None else stamp:
                qimage = self._stamp(qimage, step)
            data = encode_png(qimage)
            step.width, step.height = qimage.width(), qimage.height()
            step.sha256 = hashlib.sha256(data).hexdigest()
        elif annotations:
            raise EvidenceError("Annotations need an image.")

        with _session_lock(self.path):
            self.reload()
            step.number = len(self.steps) + 1
            step.title = step.title or f"Step {step.number}"
            if data is not None:
                step.image = self._write_new_image(step.number, step.title, data)
            self.steps.append(step)
            self._save()
        return step

    def update_step(self, ref: int | str, **changes: Any) -> EvidenceStep:
        """Change a step's text fields or status (``title``, ``status``, ``expected``,
        ``actual``, ``notes``, ``url``). ``None`` values are ignored.

        Args:
            ref: Step number, or the step's stable ``id``.

        Raises:
            EvidenceError: unknown step/field or invalid status.
        """
        editable = {"title": 300, "status": 0, "expected": 4000, "actual": 4000, "notes": 4000, "url": 2000}
        unknown = set(changes) - set(editable)
        if unknown:
            raise EvidenceError(f"Cannot change {', '.join(sorted(unknown))}; editable: {', '.join(editable)}.")
        if changes.get("status") is not None:
            normalize_status(changes["status"])  # fail before touching anything
        with _session_lock(self.path):
            self.reload()
            step = self.step(ref)
            for key, value in changes.items():
                if value is None:
                    continue
                if key == "status":
                    step.status = normalize_status(value)
                elif key == "title":
                    step.title = _clean(value, 300) or step.title
                else:
                    setattr(step, key, _clean(value, editable[key]))
            self._sync_filenames()
            self._save()
        return step

    def delete_step(self, ref: int | str) -> EvidenceStep:
        """Remove a step (and its image); later steps are renumbered.

        Args:
            ref: Step number, or the step's stable ``id``.

        Raises:
            EvidenceError: no such step.
        """
        with _session_lock(self.path):
            self.reload()
            step = self.step(ref)
            self.steps.remove(step)
            if step.image:
                try:
                    (self.path / step.image).unlink(missing_ok=True)
                except OSError as exc:
                    log.warning("Could not delete %s: %s", step.image, exc)
            self._renumber()
            self._save()
        return step

    def move_step(self, ref: int | str, new_number: int) -> EvidenceStep:
        """Move a step to position ``new_number``; files are renamed to match.

        Args:
            ref: Step number, or the step's stable ``id``.

        Raises:
            EvidenceError: the step or the target position does not exist.
        """
        with _session_lock(self.path):
            self.reload()
            step = self.step(ref)
            self.step(new_number)  # validates the target position
            self.steps.remove(step)
            self.steps.insert(new_number - 1, step)
            self._renumber()
            self._save()
        return step

    # ------------------------------------------------------------- lifecycle
    def finish(self, result: str | None = None, summary: str | None = None) -> str:
        """Mark the session finished with an overall ``result`` (default: computed).

        Returns:
            The overall result.
        """
        verdict = normalize_status(result) if result else None
        with _session_lock(self.path):
            self.reload()
            self.result = verdict or self.computed_result()
            if summary is not None:
                self.summary = _clean(summary, 8000)
            self.finished_at = now_iso()
            self._save()
        return self.result

    def export(self, formats: Sequence[str] = ("html", "pdf", "md"), *, embed_images: bool = True) -> dict[str, Path]:
        """Write the report(s) into the session folder; returns ``{format: path}``."""
        from .report import export_reports  # local import: report imports this module

        self.reload()
        return export_reports(self, formats, embed_images=embed_images)

    def to_dict(self, include_steps: bool = True) -> dict[str, Any]:
        """JSON-friendly view including absolute paths (used by the CLI and MCP)."""
        counts = self.counts()
        data: dict[str, Any] = {
            "id": self.id,
            "folder": str(self.path),
            "title": self.title,
            "test_case_id": self.test_case_id,
            "tester": self.tester,
            "environment": self.environment,
            "build": self.build,
            "description": self.description,
            "created_at": self.created_at,
            "finished_at": self.finished_at,
            "status": self.result if self.is_finished else "in_progress",
            "result_so_far": self.computed_result(),
            "summary": self.summary,
            "stamp_images": self.stamp_images,
            "step_count": counts["total"],
            "counts": {k: v for k, v in counts.items() if k != "total" and v},
        }
        if include_steps:
            data["steps"] = [self.step_dict(s) for s in self.steps]
        return data

    def step_dict(self, step: EvidenceStep) -> dict[str, Any]:
        out = step.to_dict()
        path = self.image_path(step)
        out["image"] = str(path) if path else None
        return {k: v for k, v in out.items() if v not in ("", None) or k in ("number", "title", "status")}

    # --------------------------------------------------------------- internal
    def _stamp(self, image: QImage, step: EvidenceStep) -> QImage:
        when = format_timestamp(step.captured_at)
        context = " · ".join(p for p in (step.url, self.tester, self.environment) if p)
        return stamp_footer(image, self.label, when, context)

    def _image_name(self, number: int, title: str) -> str:
        return f"{number:03d}_{slugify(title, 40)}.png"

    def _write_new_image(self, number: int, title: str, data: bytes) -> str:
        desired = self._image_name(number, title)
        stem, suffix = desired[:-4], ".png"
        name, n = desired, 2
        while True:
            try:
                with open(self.path / name, "xb") as fh:  # never overwrite an existing file
                    fh.write(data)
                return name
            except FileExistsError:
                name = f"{stem}-{n}{suffix}"
                n += 1
            except OSError as exc:
                raise EvidenceError(f"Could not save the screenshot in {self.path}: {exc}") from exc

    def _renumber(self) -> None:
        for i, step in enumerate(self.steps, 1):
            step.number = i
        self._sync_filenames()

    def _sync_filenames(self) -> None:
        """Rename image files to ``NNN_<title>.png`` after renumbering or retitling.

        Two phases (via temporary names) so swapping 001 and 002 cannot collide.
        A file that cannot be renamed (e.g. locked by a viewer) keeps its old name.
        """
        plan = [(s, self._image_name(s.number, s.title)) for s in self.steps
                if s.image and s.image != self._image_name(s.number, s.title)]
        staged: list[tuple[EvidenceStep, str]] = []
        for step, desired in plan:
            src = self.path / step.image  # type: ignore[operator]
            if not src.exists():
                step.image = desired  # nothing on disk to move; keep the manifest tidy
                continue
            tmp = f"renaming-{uuid.uuid4().hex[:8]}.png"  # a valid image name, should a rename fail
            try:
                src.rename(self.path / tmp)
            except OSError as exc:
                log.warning("Could not rename %s: %s", src.name, exc)
                continue
            step.image = tmp
            staged.append((step, desired))
        for step, desired in staged:
            final, n = desired, 2
            while (self.path / final).exists():
                final = f"{desired[:-4]}-{n}.png"
                n += 1
            try:
                (self.path / step.image).rename(self.path / final)  # type: ignore[operator]
                step.image = final
            except OSError as exc:
                log.warning("Could not rename %s to %s: %s", step.image, final, exc)


# ------------------------------------------------------------------ listing
def list_sessions(root: str | os.PathLike[str] | None = None, limit: int | None = None) -> list[EvidenceSession]:
    """Sessions under ``root``, newest first. Unreadable folders are skipped."""
    base = Path(root).expanduser() if root else default_evidence_root()
    if not base.is_dir():
        return []
    sessions = []
    for manifest in base.glob(f"*/{MANIFEST_NAME}"):
        try:
            sessions.append(EvidenceSession.open(manifest.parent))
        except Exception as exc:  # noqa: BLE001 - one broken folder must not break the listing
            log.debug("Skipping %s: %s", manifest.parent, exc)
    sessions.sort(key=lambda s: (s.created_at, s.id), reverse=True)
    return sessions[:limit] if limit is not None and limit > 0 else sessions
